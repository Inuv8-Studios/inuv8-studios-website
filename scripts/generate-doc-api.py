#!/usr/bin/env python3
"""Rebuild the website API inventory from extracted documented Unity C# scripts.
Run: python scripts/generate-doc-api.py <ArcToolkit root> <ProjectOVERRIDE root>
The script only creates metadata; it never publishes C# source code.
"""
from pathlib import Path
import json, re, sys

OUT = Path(__file__).resolve().parents[1] / 'app/doc/_lib/api.generated.ts'
if len(sys.argv) != 3:
    raise SystemExit('Usage: python scripts/generate-doc-api.py /path/to/ArcToolkit /path/to/Scripts')
ROOTS = tuple(map(Path, sys.argv[1:3]))
for root in ROOTS:
    if not root.is_dir() or not list(root.rglob('*.cs')):
        raise SystemExit(f'Expected extracted C# sources in: {root}')

def make_slug(value):
    value = re.sub(r'[^a-z0-9]+', '-', value.lower()).strip('-')
    return value

def first_summary(text):
    m = re.search(r'///\s*<summary>\s*(.*?)\s*</summary>', text, re.S)
    if not m: return ''
    return re.sub(r'\s+', ' ', re.sub(r'<[^>]+>', '', m.group(1))).strip()

def process(root):
    output=[]
    for file in sorted(root.rglob('*.cs')):
        rel=file.relative_to(root).as_posix()
        content=file.read_text(encoding='utf-8-sig',errors='replace')
        generated = ('/Input/' in '/'+rel and file.name == 'Player.cs') or '<auto-generated' in content[:500]
        symbols=[]
        for m in re.finditer(r'(?m)^\s*(?:(?:public|internal|private|protected)\s+)?(?:(?:partial|abstract|sealed|static)\s+)*(?:class|interface|struct|enum)\s+([\w]+)',content):
            if m.group(1) not in symbols: symbols.append(m.group(1))
        methods=[]
        method_docs={}
        fields=[]
        if not generated:
            # Keep only meaningful public/protected API members.
            pattern=r'(?m)^\s*(?:public|protected)\s+(?:(?:override|virtual|static|abstract|async|new|sealed)\s+)*[\w<>,\[\]\.?]+\s+([A-Za-z_]\w*)\s*\(([^\n]*)\)'
            for m in re.finditer(pattern,content):
                name=m.group(1)
                if name in methods: continue
                methods.append(name)
                preceding=content[max(0,m.start()-1400):m.start()]
                # Documentation must be adjacent to the declaration (attributes permitted).
                before_lines=preceding.splitlines()
                doc_lines=[]
                for line in reversed(before_lines):
                    stripped=line.strip()
                    if stripped.startswith('///'):
                        doc_lines.append(stripped)
                    elif stripped.startswith('[') or stripped.endswith(']') or not stripped:
                        if doc_lines: break
                        continue
                    else: break
                doc='\n'.join(reversed(doc_lines))
                summary=first_summary(doc)
                if summary: method_docs[name]=summary
            field_pat=r'(?m)^\s*(?:\[[^\]\n]+\]\s*)?public\s+(?:(?:readonly|static|const)\s+)*([\w<>\[\],.?]+)\s+([A-Za-z_]\w*)\s*(?:[;=]|\{\s*get\b)'
            for m in re.finditer(field_pat,content):
                typ,name=m.groups()
                if name not in [field['name'] for field in fields]: fields.append({'name':name,'type':typ})
        group=rel.split('/')[0]
        if root.name=='Scripts' and group=='Game': group='/'.join(rel.split('/')[:2])
        intro=content[:min(len(content),10000)]
        # Prefer the documentation immediately preceding the class, not a random later method.
        cm=re.search(r'(?m)^\s*(?:public\s+)?(?:abstract\s+)?(?:class|interface|struct|enum)\s+',content)
        description=''
        if cm:
            before=content[max(0,cm.start()-1200):cm.start()]
            sm=list(re.finditer(r'///\s*<summary>\s*(.*?)\s*</summary>',before,re.S))
            if sm:
                # Avoid attributing an earlier unrelated symbol's documentation to this class.
                tail=before[sm[-1].end():]
                if len(tail)<280: description=re.sub(r'\s+',' ',re.sub(r'<[^>]+>','',sm[-1].group(1))).strip()
        output.append({'id':make_slug(rel[:-3]),'file':file.name,'path':rel,'group':group,'symbols':symbols[:12],'methods':methods[:65], 'methodDocs':method_docs, 'fields':fields[:55], 'description':description or ('Generated Input System wrapper.' if generated else ''),'generated':generated})
    return output

arc,game=(process(root) for root in ROOTS)
OUT.parent.mkdir(parents=True,exist_ok=True)
OUT.write_text('/* Generated by scripts/generate-doc-api.py. Do not edit by hand. */\n'+
 'import type { ApiEntry } from "./types";\n'+
 'export const arcApi: ApiEntry[] = '+json.dumps(arc,indent=2,ensure_ascii=False)+';\n'+
 'export const overrideApi: ApiEntry[] = '+json.dumps(game,indent=2,ensure_ascii=False)+';\n',encoding='utf-8')
print(f'Generated {len(arc)} ArcToolkit and {len(game)} ProjectOVERRIDE C# file entries -> {OUT}')
